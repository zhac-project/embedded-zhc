// Endpoint slot (EP2 = input_1, EP3 = input_2) x scene event. Static literals
// because the action is published as a StringRef.
constexpr const char* kInputActions_S4DM_0A101WWL[2][5] = {
    {"input_1_single", "input_1_double", "input_1_triple", "input_1_hold", "input_1_toggle"},
    {"input_2_single", "input_2_double", "input_2_triple", "input_2_hold", "input_2_toggle"},
};

bool fz_s4dm_input_scene(const DecodedMessage& msg, const FzConverter&,
                         const PreparedDefinition&, RuntimeContext&,
                         FixedPayload<ZHC_FIXED_PAYLOAD_CAP>& out) {
    if (msg.src_endpoint != 2 && msg.src_endpoint != 3) return false;
    if (msg.raw_body.size() < 3) return false;   // group u16 LE, scene u8
    int event = -1;
    switch (msg.raw_body[2]) {
        case 1:  event = 0; break;   // single
        case 2:  event = 1; break;   // double
        case 3:  event = 2; break;   // triple
        case 4:                      // hold
        case 11: event = 3; break;   // hold
        case 5:  event = 4; break;   // toggle
        default: return false;
    }
    Value a{}; a.type = ValueType::StringRef;
    a.str = kInputActions_S4DM_0A101WWL[msg.src_endpoint - 2][event];
    return out.put("action", a);
}

