// kFzTuyaButtonAction handles cmd 0xFD (commandTuyaAction). The previous
// kFzTuyaOnOffAction only mapped 0x00/0x01/0x02 (on/off/toggle), so real
// presses (cmd 0xFD payload 0/1/2 = single/double/hold per src_endpoint)
// fell through with "(no match)" and shadow stayed empty.
// z2m v26.105.0 TS0044 = tuyaBase() + m.battery({voltage: true,
// percentageReporting: false}) + tuya.fz.on_off_action; the generator emitted
// only the action half, dropping battery for every TS0044. The shared generic
// converter decodes the battery (0x0020 → voltage mV, 0x0021 → battery %);
// m.battery configures no reporting with those arguments.
