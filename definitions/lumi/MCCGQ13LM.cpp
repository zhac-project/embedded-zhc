constexpr std::uint16_t kLumiManu = 0x115F;

// DeviceRuntimeState::scratch[0] = a press was seen, scratch[1] = its tsn.
bool fz_p1_action(const DecodedMessage& msg, const FzConverter&, const PreparedDefinition&,
                  RuntimeContext& ctx, FixedPayload<ZHC_FIXED_PAYLOAD_CAP>& out) {
    const Value* v = msg.payload.find("5");   // modelId
    if (!v || v->type != ValueType::BytesRef) return false;
    const std::string_view model(reinterpret_cast<const char*>(v->bytes.data()), v->bytes.size());
    if (model != "lumi.magnet.ac01") return false;
    if (auto* st = ctx.device_state()) {
        if (st->scratch[0] && st->scratch[1] == msg.transaction_sequence) return false;
        st->scratch[0] = 1;
        st->scratch[1] = msg.transaction_sequence;
    }
    Value a{}; a.type = ValueType::StringRef; a.str = "single";
    return out.put("action", a);
}

bool fz_p1_battery(const DecodedMessage& msg, const FzConverter&, const PreparedDefinition&,
                   RuntimeContext&, FixedPayload<ZHC_FIXED_PAYLOAD_CAP>& out) {
    const Value* v = msg.payload.find("32");   // batteryVoltage, 100 mV
    if (!v || v->type != ValueType::Uint || v->u >= 255) return false;
    const std::uint32_t mv = static_cast<std::uint32_t>(v->u) * 100;
    const std::uint32_t clamped = mv < 2850 ? 2850 : mv > 3000 ? 3000 : mv;
    Value volt{}; volt.type = ValueType::Uint; volt.u = mv;
    Value pct{};  pct.type  = ValueType::Uint; pct.u  = ((clamped - 2850) * 100 + 75) / 150;   // z2m rounds
    out.put("voltage", volt);
    out.put("battery", pct);
    return true;
}

constexpr FzConverter zcl_fz(const char* cluster, std::uint32_t types, FromZigbeeFn fn) {
    return FzConverter{
        .family            = FrameFamily::Zcl,
        .cluster           = cluster,
        .type_mask         = types,
        .command_id        = WILDCARD_CMD_ID,
        .attr_id           = WILDCARD_ATTR_ID,
        .endpoint          = WILDCARD_ENDPOINT,
        .frame_flags_mask  = 0,
        .frame_flags_value = 0,
        .direction         = Direction::ServerToClient,
        .fn                = { .zcl_fn = fn },
        .user_config       = nullptr,
    };
}
constexpr FzConverter kFzP1Action = zcl_fz("genBasic", type_bit(MessageType::AttributeReport), fz_p1_action);
constexpr FzConverter kFzP1Battery = zcl_fz(
    "genPowerCfg", type_bit(MessageType::AttributeReport) | type_bit(MessageType::ReadResponse), fz_p1_battery);

constexpr ::zhc::generic::ZclWriteLookup kDistances[] = { {"10mm", 1}, {"20mm", 2}, {"30mm", 3} };
constexpr ::zhc::generic::ZclAttrRow kDistanceRows[] = { { 0x010C, "detection_distance", 1, kDistances, 3 } };
constexpr ::zhc::generic::ZclAttrMap kDistanceMap{ kDistanceRows, 1, kLumiManu };
constexpr FzConverter kFzDetectionDistance = ::zhc::generic::zcl_attr_fz("manuSpecificLumi", &kDistanceMap);
constexpr ::zhc::generic::ZclWriteSpec kDistanceSpec{ "detection_distance", 0x010C, 0x20, kLumiManu, kDistances, 3 };
constexpr TzConverter kTzDetectionDistance = ::zhc::generic::zcl_write_tz("manuSpecificLumi", 0xFCC0, &kDistanceSpec);

